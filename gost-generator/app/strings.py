# Каркас для английского перевода (п. 13: «Английский интерфейс» — задел v2).
EN: dict[str, str] = {
    "tab_generator": "Generation",
    "tab_rules": "Rules",
    "tab_checker": "Checker",
    "tab_profile": "Profile",
    "btn_settings": "Settings",
    "btn_about": "About",
}


def t(text_key: str, lang: str | None = None, **fmt: object) -> str:
    """Вернуть строку по ключу; отсутствующий ключ отдаётся как есть ( видно в UI ).

    Форматирование — `str.format` с переданными аргументами; некорректные
    плейсхолдеры не роняют интерфейс. Первый параметр не называется `key`,
    потому что строки форматируют плейсхолдером `{key}` (rules_saved, prof_created).
    """
    table = EN if (lang == "en" and text_key in EN) else T
    template = table.get(text_key, text_key)
    if not fmt:
        return template
    try:
        return template.format(**fmt)
    except (KeyError, IndexError, ValueError):
        return template
